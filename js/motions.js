export function poseStrokes(family, frame = 0) {
  const p =
    (POSES[family] || POSES.walk)[frame] || (POSES[family] || POSES.walk)[0];
  const circle = Array.from({ length: 25 }, (_, i) => [
    p[0][0] + 13 * Math.cos((i * Math.PI) / 12),
    p[0][1] + 13 * Math.sin((i * Math.PI) / 12),
  ]);
  return [
    circle,
    [p[0], p[1], p[2]],
    [p[1], p[3], p[4]],
    [p[1], p[5], p[6]],
    [p[2], p[7], p[8]],
    [p[2], p[9], p[10]],
  ];
}
